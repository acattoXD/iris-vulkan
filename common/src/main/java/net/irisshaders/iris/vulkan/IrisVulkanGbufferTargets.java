	public static void bindSamplers(RenderPass pass, GpuTextureView depth0, GpuTextureView depth1, GpuTextureView depth2) {
		if (!ready()) {
			return;
		}

		GpuSampler sampler = RenderSystem.getSamplerCache().getClampToEdge(FilterMode.NEAREST);

		for (int i = 0; i < COLOR_TARGET_COUNT; i++) {
			GpuTextureView view = currentView(i);
			if (view != null) {
				pass.setUniform("colortex" + i, view, samplerForTarget(view));
			}
		}

		bindAlias(pass, "InSampler", FALLBACK_SCENE_TARGET);
		bindAlias(pass, "Sampler0", FALLBACK_SCENE_TARGET);
		bindAlias(pass, "u_MainSampler", FALLBACK_SCENE_TARGET);
		bindAlias(pass, "texture", FALLBACK_SCENE_TARGET);
		bindAlias(pass, "tex", FALLBACK_SCENE_TARGET);
		bindAlias(pass, "composite", 3);
		bindAlias(pass, "gcolor", 0);
		bindAlias(pass, "gdepth", 1);
		bindAlias(pass, "gnormal", 2);
		bindAlias(pass, "gaux1", 4);
		bindAlias(pass, "gaux2", 5);
		bindAlias(pass, "gaux3", 6);
		bindAlias(pass, "gaux4", 7);

		bindDepth(pass, "depthtex0", depth0, sampler);
		bindDepth(pass, "depthtex1", depth1, sampler);
		bindDepth(pass, "depthtex2", depth2, sampler);
		bindDepth(pass, "gdepthtex", depth0, sampler);
	}

